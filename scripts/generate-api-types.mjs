// Generates src/api/generated.ts from a Jellyfin server's OpenAPI document: one type per schema.
// The app's own types (src/api/types.ts) are cut out of these, so a field that is misspelt, no
// longer exists or changed its type fails the type check.
//
//   npm run generate:api                      (server at http://localhost:8096)
//   JELLYFIN_URL=http://host:8096 npm run generate:api
import { writeFile } from 'node:fs/promises';

const server = (process.env.JELLYFIN_URL || 'http://localhost:8096').replace(/\/+$/, '');
const source = `${server}/api-docs/openapi.json`;

const response = await fetch(source);
if (!response.ok) throw new Error(`${source} answered ${response.status}`);
const doc = await response.json();
const schemas = doc.components?.schemas ?? {};

const ident = (name) => name.replace(/[^A-Za-z0-9_$]/g, '_');
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** The TypeScript type for one JSON schema. */
function type(schema, indent = '') {
  if (!schema) return 'unknown';
  let t;
  if (schema.$ref) t = ident(schema.$ref.split('/').pop());
  else if (schema.enum) t = schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  else if (schema.allOf || schema.oneOf || schema.anyOf) {
    const parts = (schema.allOf ?? schema.oneOf ?? schema.anyOf).map((s) => type(s, indent));
    t = parts.length === 1 ? parts[0] : `(${parts.join(schema.allOf ? ' & ' : ' | ')})`;
  } else if (schema.type === 'array') {
    const item = type(schema.items, indent);
    t = /[ |&]/.test(item) ? `(${item})[]` : `${item}[]`;
  } else if (schema.type === 'object' || schema.properties) {
    const inner = `${indent}  `;
    const lines = Object.entries(schema.properties ?? {}).map(([name, prop]) => {
      // The server's descriptions of its fields are left out: they are its documentation, under
      // its licence. The names and types are what the API is.
      return `${inner}${key(name)}${required ? '' : '?'}: ${type(prop, inner)};`;
    });
    if (schema.additionalProperties) {
      lines.push(`${inner}[key: string]: ${schema.additionalProperties === true ? 'unknown' : type(schema.additionalProperties, inner)};`);
    }
    t = lines.length ? `{\n${lines.join('\n')}\n${indent}}` : 'Record<string, unknown>';
  } else if (schema.type === 'integer' || schema.type === 'number') t = 'number';
  else if (schema.type === 'boolean') t = 'boolean';
  else if (schema.type === 'string') t = 'string';
  else t = 'unknown';
  return schema.nullable ? `${t} | null` : t;
}

const names = Object.keys(schemas).sort();
const out = [
  `// Generated by scripts/generate-api-types.mjs from Jellyfin ${doc.info?.version ?? ''}. Do not edit:`,
  '// run `npm run generate:api` against a newer server instead.',
  '',
];
for (const name of names) {
  const schema = schemas[name];
  const body = type(schema);
  out.push(
    body.startsWith('{') && !schema.nullable ? `export interface ${ident(name)} ${body}` : `export type ${ident(name)} = ${body};`,
    '',
  );
}
await writeFile(new URL('../src/api/generated.ts', import.meta.url), out.join('\n'));
console.log(`src/api/generated.ts written from Jellyfin ${doc.info?.version ?? '?'} (${names.length} types)`);
